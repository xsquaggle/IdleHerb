/**
 * Generates floors/wN.yaml from floors/template.yaml and worlds/worlds.yaml (GDD 5.3).
 * Run with `pnpm content:floors`. The output is committed, so a regenerated
 * table shows up as an ordinary diff (docs/tech/04-content-pipeline.md).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';
import { Num, numToSave } from '@sprout/core';
import { generateFloors, type FloorTemplate } from '../../src/floor-template';

const here = dirname(fileURLToPath(import.meta.url));
const template = parse(readFileSync(join(here, 'template.yaml'), 'utf8')) as FloorTemplate;
const worlds = parse(readFileSync(join(here, '../worlds/worlds.yaml'), 'utf8')) as { id: string; order: number; D: string; T: number; floors: number }[];

function show(n: Num): string {
  // Whole numbers below 1e15 are written in full; anything else in exact mantissa-exponent form.
  if (n.lt(1e15) && Number.isInteger(n.toNumber())) return String(n.toNumber());
  if (n.lt(1e15)) return String(Number(n.toNumber().toPrecision(15)));
  return JSON.stringify(numToSave(n));
}

for (const w of worlds) {
  const rows = generateFloors(template, { id: w.id, D: Num.from(w.D), T: w.T, floors: w.floors });
  const lines = [
    `# GENERATED by floors/generate.ts from floors/template.yaml and worlds/worlds.yaml. Do not edit by hand.`,
    `# ${w.id}: D = ${w.D}, T = ${w.T}`,
  ];
  for (const r of rows) {
    lines.push(
      `- { id: ${r.id}, world: ${w.id}, order: ${r.order}, favouredFamily: ${r.favouredFamily}, ` +
        `openCost: ${show(r.openCost)}, basePayout: ${show(r.basePayout)}, baseCycleSec: ${r.baseCycleSec}, ` +
        `levelCost: { base: ${show(r.levelBaseCost)}, growth: ${r.growth} }, hireFee: ${show(r.hireFee)} }`,
    );
  }
  writeFileSync(join(here, `w${w.order}.yaml`), lines.join('\n') + '\n');
  console.log(`wrote floors/w${w.order}.yaml (${rows.length} floors)`);
}
